export const bundles: Record<Locale, Bundle> = { en, fr, pt };

// The iframe's language is fixed for the session, so it is read once.
let resolved: Locale | null = null;

export function resolveLocale(): Locale {
  if (resolved) return resolved;
  let loc = '';
  try {
    loc = (getOpenldr().locale ?? '').slice(0, 2).toLowerCase();
  } catch {
    loc = '';
  }
  resolved = loc === 'fr' || loc === 'pt' ? loc : 'en';
  return resolved;
}

/** Test-only: forget the language so a test can set its own. */
export function resetLocale(): void {
  resolved = null;
}

/** The string for `key` in the page language, falling back to English, then to the key. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const value = bundles[resolveLocale()][key] ?? en[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Whether a string exists for `key`. Lets a caller fall back to a raw code. */
export function has(key: string): boolean {
  return key in en;
}

export function formatNumber(n: number): string {
  return new Intl.NumberFormat(resolveLocale()).format(n);
}
