export const bundles: Record<Locale, Bundle> = { en, fr, pt };

// The iframe's language is fixed for the session, so it is read once.
let resolved: Locale | null = null;

export function resolveLocale(): Locale {
  if (resolved) return resolved;
  let loc = '';
  try {
    loc = (getOpenldr().locale ?? '').slice(0, 2).toLowerCase();
  } catch {
    loc = '';
  }
  resolved = loc === 'fr' || loc === 'pt' ? loc : 'en';
  return resolved;
}

/** Test-only: forget the language so a test can set its own. */
export function resetLocale(): void {
  resolved = null;
}

/** The string for `key` in the page language, falling back to English, then to the key. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const value = bundles[resolveLocale()][key] ?? en[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Whether a string exists for `key`. Lets a caller fall back to a raw code. */
export function has(key: string): boolean {
  return key in en;
}

export function formatNumber(n: number): string {
  return new Intl.NumberFormat(resolveLocale()).format(n);
}

const SIZE_UNITS = ['B', 'KiB', 'MiB', 'GiB', 'TiB'] as const;

/** A byte count in binary units (1 KiB is 1024 bytes), one decimal place, in the page language. */
export function formatBytes(n: number): string {
  let value = Math.max(0, n);
  let unit = 0;
  // Compare the rounded value, so 1023.96 KiB shows as 1.0 MiB, not 1,024.0 KiB.
  while (unit < SIZE_UNITS.length - 1 && Math.round(value * 10) / 10 >= 1024) {
    value /= 1024;
    unit += 1;
  }
  const digits = unit === 0 ? 0 : 1;
  const shown = new Intl.NumberFormat(resolveLocale(), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value);
  return `${shown} ${t(`size.${SIZE_UNITS[unit]}`)}`;
}

/** A stored ISO time as a date and time in the page language. */
export function formatTime(iso: string): string {
  const at = new Date(iso);
  if (Number.isNaN(at.getTime())) return iso;
  return new Intl.DateTimeFormat(resolveLocale(), { dateStyle: 'medium', timeStyle: 'short' }).format(at);
}
